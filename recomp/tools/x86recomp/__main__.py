"""Recompile the DLC game exe into C.

  python -m x86recomp GAME_EXE OUT_DIR

Writes OUT_DIR/code_NNN.c (the lifted functions), funcs.h, dispatch.c,
imports.c and functions.tsv (one row per function, for naming work).
"""
import argparse
import collections
import os
import time

from .discover import Program
from .image import Image
from .lift import Lifter

INSNS_PER_FILE = 8000
BIG_FUNC = 2500  # functions this long get their own big_*.c, built at -O1

HEADER = '/* Generated by tools/x86recomp. Do not edit. */\n#include "x86rt.h"\n#include "funcs.h"\n\n'


def main():
    ap = argparse.ArgumentParser(prog="x86recomp")
    ap.add_argument("exe")
    ap.add_argument("out")
    a = ap.parse_args()
    t0 = time.time()
    img = Image(a.exe)
    prog = Program(img)
    funcs = prog.discover()
    print(f"{len(funcs)} functions, {sum(len(f.insns) for f in funcs.values())} insns "
          f"({time.time() - t0:.0f} s)")

    names = {va: f"F_{va:08x}" for va in funcs}
    os.makedirs(a.out, exist_ok=True)
    # files whose text is unchanged are left as they are (their objects stay current); stale ones go at the end
    old_files = {fn for fn in os.listdir(a.out)
                 if (fn.startswith("code_") or fn.startswith("big_")) and fn.endswith(".c")}
    written = set()

    class put:
        def __init__(self, path, mode="w"):
            self.path, self.parts = path, []
        def __enter__(self):
            return self
        def write(self, text):
            self.parts.append(text)
        def __exit__(self, *exc):
            if exc[0]:
                return False
            text = "".join(self.parts)
            written.add(os.path.basename(self.path))
            try:
                with open(self.path) as fh:
                    if fh.read() == text:
                        return False
            except OSError:
                pass
            with open(self.path, "w") as fh:
                fh.write(text)
            return False

    unimpl = collections.Counter()
    rows = []
    chunk, count, idx = [], 0, 0

    def flush():
        nonlocal chunk, count, idx
        if chunk:
            with put(os.path.join(a.out, f"code_{idx:03d}.c")) as fh:
                fh.write(HEADER + "\n".join(chunk))
            idx += 1
        chunk, count = [], 0

    for va in sorted(funcs):
        f = funcs[va]
        lf = Lifter(prog, f, names)
        text = lf.lift_function()
        n_un = text.count("rt_unimpl(")
        for line in text.splitlines():
            if "rt_unimpl(" in line:
                unimpl[line.split('"')[1].split(" ")[0]] += 1
        if len(f.insns) >= BIG_FUNC:
            with put(os.path.join(a.out, f"big_{va:08x}.c")) as fh:
                fh.write(HEADER + text)
        else:
            chunk.append(text)
            count += len(f.insns)
        span = max(f.insns) - va if f.insns else 0
        rows.append(f"{va:08x}\t{span}\t{len(f.insns)}\t{n_un}\t{len(f.calls)}")
        if count >= INSNS_PER_FILE:
            flush()
    flush()

    with put(os.path.join(a.out, "funcs.h")) as fh:
        fh.write("/* Generated by tools/x86recomp. */\n#pragma once\n#include \"x86rt.h\"\n")
        for va in sorted(funcs):
            fh.write(f"void {names[va]}(CPU *c);\n")

    # Dispatch: function bodies plus every ILT thunk that leads to one
    disp = {va: names[va] for va in funcs}
    for thunk in img.ilt:
        t = prog.resolve(thunk)
        if t in funcs:
            disp[thunk] = names[t]
    with put(os.path.join(a.out, "dispatch.c")) as fh:
        fh.write(HEADER + "const RtFunc rt_funcs[] = {\n")
        for va in sorted(disp):
            fh.write(f"    {{0x{va:08x}u, {disp[va]}}},\n")
        fh.write(f"}};\nconst uint32_t rt_funcs_count = {len(disp)};\n")

    with put(os.path.join(a.out, "conts.c")) as fh:
        fh.write('/* Generated by tools/x86recomp. */\n#include "x86rt.h"\n\n/* exception continuation -> owning function */\nconst RtCont rt_conts[] = {\n')
        n = 0
        for cva in sorted(prog.conts):
            for fva in prog.conts[cva]:
                fh.write(f"    {{0x{cva:08x}u, 0x{fva:08x}u}},\n")
                n += 1
        fh.write(f"    {{0, 0}}}};\nconst uint32_t rt_conts_count = {n};\n")

    with put(os.path.join(a.out, "imports.c")) as fh:
        fh.write('/* Generated by tools/x86recomp. */\n#include "x86rt.h"\n\nconst RtImport rt_imports[] = {\n')
        for iat in sorted(img.imports):
            dll, name = img.imports[iat]
            fh.write(f'    {{0x{iat:08x}u, "{dll}", "{name}"}},\n')
        fh.write(f"}};\nconst uint32_t rt_imports_count = {len(img.imports)};\n")

    with put(os.path.join(a.out, "image.h")) as fh:
        fh.write("/* Generated by tools/x86recomp. */\n#pragma once\n")
        fh.write(f"#define GAME_IMAGE_BASE 0x{img.base:08x}u\n#define GAME_IMAGE_SIZE 0x{img.size:08x}u\n")
        fh.write(f"#define GAME_ENTRY 0x{img.entry:08x}u\n")

    with open(os.path.join(a.out, "functions.tsv"), "w") as fh:
        fh.write("va\tspan\tinsns\tunimpl\tcalls\n" + "\n".join(rows) + "\n")

    for fn in old_files - written:
        os.remove(os.path.join(a.out, fn))
    print(f"wrote {idx} code files ({time.time() - t0:.0f} s)")
    print(f"unimplemented sites: {sum(unimpl.values())}")
    for m, k in unimpl.most_common(40):
        print(f"  {m} {k}")


if __name__ == "__main__":
    main()
