#!/usr/bin/env python3
"""embed_art.py ART_DIR OUT.c: the overlay's pictures (port_art/*.png) as byte arrays, so the NRO needs
no files beside it. A file in the game folder's port/ still overrides its copy (overlay.c)."""
import os, sys

names = ["help_buttons.png", "help_buttons_small.png", "shovelmeter_empty.png", "shovelmeter_full.png", "pad_icon.png",
         "sign_329x143.png", "sign_313x133.png", "sign_286x122.png", "sign_266x123.png", "sign_322x142.png",
         "signlit_329x143_1.png", "signlit_313x133_0.png", "signlit_286x122_0.png", "signlit_266x123_0.png", "signlit_322x142_1.png"]
art, out = sys.argv[1], sys.argv[2]
with open(out, "w") as f:
    f.write("/* generated by tools/embed_art.py from port_art/: do not edit */\n#include <stddef.h>\n\n")
    for i, n in enumerate(names):
        data = open(os.path.join(art, n), "rb").read()
        f.write("static const unsigned char art_%d[%d] = {\n" % (i, len(data)))
        for k in range(0, len(data), 24):
            f.write("    " + ", ".join(str(b) for b in data[k:k + 24]) + ",\n")
        f.write("};\n")
    f.write("const struct { const char *name; const unsigned char *data; size_t size; } ov_embedded[] = {\n")
    for i, n in enumerate(names):
        f.write('    {"%s", art_%d, sizeof art_%d},\n' % (n, i, i))
    f.write("    {NULL, NULL, 0},\n};\n")
